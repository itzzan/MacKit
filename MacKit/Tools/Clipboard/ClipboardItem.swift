import AppKit
import CryptoKit
import UniformTypeIdentifiers

enum ClipboardKind: String, Codable {
    case text, richText, image, file
}

/// 一条剪贴板记录里的一种格式。小的直接放在列表文件里，大的单独存成文件
struct ClipboardEntry: Codable, Equatable {
    let type: String
    var inline: Data?
    var blob: String?
}

/// 一条剪贴板历史
struct ClipboardItem: Codable, Identifiable, Equatable {
    let id: UUID
    /// 原样记下的剪贴板内容：每个"剪贴板项"（复制多个文件时有好几个）的全部格式
    var pasteboardItems: [[ClipboardEntry]]
    var kind: ClipboardKind
    var title: String
    var searchText: String
    var imagePixelSize: CGSize?
    var fileCount: Int
    var fingerprint: String
    var sourceBundleID: String?
    var sourceName: String?
    var firstCopied: Date
    var lastCopied: Date
    var copyCount: Int
    /// 收藏（台阶 14 起"置顶"升级成"收藏"，存盘的名字没改，老的置顶自动算收藏）
    var pinned: Bool
    /// 收藏时起的名字（"公司地址"），没起就是 nil
    var favoriteName: String? = nil
    /// 在收藏栏里排第几（小的在前）；老文件里没有，按原来的先后
    var favoriteOrder: Int? = nil
    /// 放在哪个收藏分组里（台阶 23，存组的编号；nil = 不分组）
    var favoriteGroup: UUID? = nil

    var isFavorite: Bool { pinned }
    /// 列表里显示的名字：起了名字用名字
    var displayTitle: String { favoriteName ?? title }
}

/// 收藏分组（台阶 23）："工作""生活"……一条收藏只放进一个组（像文件夹）
struct ClipboardGroup: Codable, Identifiable, Equatable {
    let id: UUID
    var name: String
}

/// 刚从剪贴板读到、还没存的内容
struct ClipboardSnapshot {
    var pasteboardItems: [[(type: String, data: Data)]]
    var kind: ClipboardKind
    var title: String
    var searchText: String
    var imagePixelSize: CGSize?
    var fileCount: Int
    var fingerprint: String
    var sourceBundleID: String?
    var sourceName: String?
    var totalBytes: Int
}

/// 读剪贴板：决定记不记、记成什么
@MainActor
enum ClipboardReader {
    /// MacKit 把历史放回剪贴板时打的标记：看到它就不再记一遍
    static let restoreMarker = NSPasteboard.PasteboardType("local.mackit.clipboard.restore")
    static let maxBytes = 20 * 1024 * 1024

    /// 保密、临时、自动生成的内容不记（nspasteboard.org 的约定，Maccy 也这么做），还有常见密码管理器的标记
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "net.antelle.keeweb", "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping", "Pasteboard generator type",
    ]

    enum Skip: Error, Equatable { case empty, ignored, ownRestore, tooBig, ignoredApp }

    /// ignoredApps：名单里的软件复制的不记（台阶 14）
    static func read(_ pb: NSPasteboard, source: NSRunningApplication? = NSWorkspace.shared.frontmostApplication,
                     ignoredApps: Set<String>? = nil) -> Result<ClipboardSnapshot, Skip> {
        let ignoredApps = ignoredApps ?? Set(Settings.clipboardIgnoredApps)
        let allTypes = Set((pb.types ?? []).map(\.rawValue))
        if allTypes.contains(restoreMarker.rawValue) { return .failure(.ownRestore) }
        if !allTypes.isDisjoint(with: ignoredTypes) { return .failure(.ignored) }
        if let id = source?.bundleIdentifier, ignoredApps.contains(id) { return .failure(.ignoredApp) }
        guard let pbItems = pb.pasteboardItems, !pbItems.isEmpty else { return .failure(.empty) }

        var items: [[(type: String, data: Data)]] = []
        var total = 0
        for item in pbItems {
            var entries: [(type: String, data: Data)] = []
            for type in item.types {
                guard let data = item.data(forType: type) else { continue }
                entries.append((type.rawValue, data))
                total += data.count
                if total > maxBytes { return .failure(.tooBig) }
            }
            if !entries.isEmpty { items.append(entries) }
        }
        guard let first = items.first else { return .failure(.empty) }

        // 来源：复制时有的软件会写 org.nspasteboard.source；没有就用当时在前台的软件
        let sourceID = pb.string(forType: NSPasteboard.PasteboardType("org.nspasteboard.source")) ?? source?.bundleIdentifier
        let sourceName = sourceID.flatMap { id in
            NSWorkspace.shared.urlForApplication(withBundleIdentifier: id).map { FileManager.default.displayName(atPath: $0.path) }
        } ?? source?.localizedName

        // 文件（访达里复制的）
        let fileURLs = pbItems.compactMap { $0.string(forType: .fileURL) }.compactMap { URL(string: $0) }.filter(\.isFileURL)
        if !fileURLs.isEmpty {
            let names = fileURLs.map(\.lastPathComponent)
            let title = names.count == 1 ? names[0] : "\(names[0]) 等 \(names.count) 个文件"
            return .success(snapshot(items, .file, title, names.joined(separator: " "), nil, fileURLs.count,
                                     fingerprint(["file"] + fileURLs.map(\.path)), sourceID, sourceName, total))
        }

        // 按复制来源给的格式顺序：先碰到图片就是图片，先碰到文字就是文字
        let string = pb.string(forType: .string)
        for (type, data) in first {
            guard let ut = UTType(type) else { continue }
            if ut.conforms(to: .image), !ut.conforms(to: .pdf), let rep = NSBitmapImageRep(data: data) {
                let size = CGSize(width: rep.pixelsWide, height: rep.pixelsHigh)
                return .success(snapshot(items, .image, "图片 \(rep.pixelsWide)×\(rep.pixelsHigh)", "图片", size, 0,
                                         fingerprint(["image"], data: data), sourceID, sourceName, total))
            }
            if ut.conforms(to: .text), let text = string, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
                let rich = first.contains { $0.type == NSPasteboard.PasteboardType.rtf.rawValue
                    || $0.type == NSPasteboard.PasteboardType.html.rawValue
                    || $0.type == NSPasteboard.PasteboardType.rtfd.rawValue }
                return .success(snapshot(items, rich ? .richText : .text, ClipboardText.title(from: text),
                                         String(text.prefix(10_000)), nil, 0, fingerprint(["text", text]),
                                         sourceID, sourceName, total))
            }
        }
        if let text = string, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return .success(snapshot(items, .text, ClipboardText.title(from: text), String(text.prefix(10_000)), nil, 0,
                                     fingerprint(["text", text]), sourceID, sourceName, total))
        }
        return .failure(.empty)
    }

    private static func snapshot(_ items: [[(type: String, data: Data)]], _ kind: ClipboardKind, _ title: String,
                                 _ search: String, _ size: CGSize?, _ files: Int, _ fp: String,
                                 _ sourceID: String?, _ sourceName: String?, _ total: Int) -> ClipboardSnapshot {
        ClipboardSnapshot(pasteboardItems: items, kind: kind, title: title, searchText: search, imagePixelSize: size,
                          fileCount: files, fingerprint: fp, sourceBundleID: sourceID, sourceName: sourceName,
                          totalBytes: total)
    }

    /// 同一内容（同一段字、同一张图、同一批文件）指纹相同，用来去重
    static func fingerprint(_ parts: [String], data: Data? = nil) -> String {
        var hasher = SHA256()
        for part in parts { hasher.update(data: Data(part.utf8)); hasher.update(data: Data([0])) }
        if let data { hasher.update(data: data) }
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }
}
